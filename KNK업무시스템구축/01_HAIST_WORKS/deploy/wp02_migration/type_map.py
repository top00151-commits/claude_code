"""WP-02 · SQLite → PostgreSQL 타입 매핑 — **KNK 기존 표기 규정을 그대로 따른다**

근거 규정 (전부 기존 확정 사항 · 이 문서에서 새로 만든 규칙 없음):
  · z1048 (2026-07-24 대표 지시)   수량 = 정수. 소수가 정당한 칸만 예외(중량·환율 등)
  · z1026 (2026-07-21 대표 확정)   원화 = 정수 / 외화(인보이스) = 소수 2자리·셋째에서 반올림
                                   판매단가 = 매입 × (1+마진%) — 소수점 이하 버림
  · z1024                          외화 왕복 반올림 금지 — KRW 원본이 단일 소스
  · KNK 시간대 표준 v1 (2026-06-09) 날짜 경계 = 입력자 소속 시간대(본사 +9 / 베트남 +7)
  · WP-02 대표 결정 (2026-07-24)   1차 이관은 날짜를 **글자 그대로** 유지

실측 근거 (사본 `.wp02_rehearsal.db` · 2026-07-24):
  · 수량 성격 컬럼 10개 · 소수값 **0건**            → 정수형으로 안전
  · 금액에 KRW·USD·EUR·(미지정)이 **한 컬럼에 혼재** → 컬럼 단위로 "원화=정수"를 강제할 수 없음
    → 저장 타입은 numeric(20,2)로 두고, 원화 정수 규정은 **애플리케이션에서 강제**(현행과 동일)
  · double precision 으로 옮기면 큰 금액에서 **19,460원 오차** 발생 → 금액은 반드시 numeric
"""
import re

# ── 이름으로 성격을 판별한다. 판별 규칙은 z1048 검사기와 같은 원칙을 쓴다
#    (단어경계 `[^a-z]` 금지 — camelCase 를 놓친다. z1048 교훈)
RE_QTY = re.compile(r"(qty|quantity|수량|count|cnt)", re.I)
RE_MONEY = re.compile(r"(amount|amt|price|cost|total|balance|paid|budget|fee|krw|usd|vat|tax_invoice_amt)", re.I)
RE_DECIMAL_OK = re.compile(r"(rate|ratio|pct|percent|margin|weight|kg|cbm|fx|score|lat|lng|temp)", re.I)
RE_DATETIME = re.compile(r"(_at$|_date$|^date_|_datetime$|_time$)", re.I)

# 수량이지만 소수가 정당한 예외 (규정의 `data-knk-decimal` 에 대응)
QTY_DECIMAL_EXCEPTIONS = {
    # (표, 컬럼) — 실측에서 소수가 발견되면 여기에 등재하고 근거를 남긴다. 현재 0건.
}

# 금액 타입 = **정밀도 제한 없는 numeric**
#   왜 numeric(20,2)가 아닌가 — 실측(2026-07-24)으로 확인한 두 가지 때문:
#     ① 소수부가 최대 **16자리**인 값이 실재한다(부동소수점 계산 찌꺼기).
#        numeric(20,2)로 받으면 반올림되어 합계가 달라진다(order_items.unit_price 0.0145 차이 실측).
#     ② 정수부가 **20자리**인 이상값이 있어 numeric(20,2)는 overflow 로 이관 자체가 실패했다.
#   1차 이관의 최우선 원칙은 **원본 보존**이다(날짜를 글자 그대로 두기로 한 대표 결정과 같은 철학).
#   따라서 값은 그대로 담고, z1026(원화=정수·외화 2자리)은 **애플리케이션에서 강제**한다 — 현행과 동일.
#   자릿수 정리·이상값 판정은 별도 정제 단계에서 근거를 남기고 수행한다.
MONEY_TYPE = "numeric"
QTY_TYPE = "bigint"           # z1048 수량=정수 (실측: 수량 컬럼 10개·소수 0건)
QTY_DECIMAL_TYPE = "numeric"
RATIO_TYPE = "numeric"        # 환율·마진·중량 — 소수 정당(z1048 예외)
DATE_TYPE = "text"            # WP-02 대표 결정: 1차는 글자 그대로


def classify(table: str, column: str, decl: str) -> tuple:
    """(PostgreSQL 타입, 분류, 근거규정) 반환."""
    d = (decl or "").upper().split("(")[0].strip()

    if d == "BLOB":
        return "bytea", "이진", "-"
    if RE_DATETIME.search(column):
        return DATE_TYPE, "날짜·시각", "WP-02 대표결정(1차 글자 유지)+시간대표준 v1"
    if d not in ("INTEGER", "REAL"):
        return "text", "글자", "-"

    if RE_DECIMAL_OK.search(column):
        return RATIO_TYPE, "비율·환율·중량", "z1048 예외(소수 정당)"
    if RE_QTY.search(column):
        if (table, column) in QTY_DECIMAL_EXCEPTIONS:
            return QTY_DECIMAL_TYPE, "수량(소수 예외)", "z1048 data-knk-decimal 대응"
        return QTY_TYPE, "수량", "z1048 수량=정수"
    if RE_MONEY.search(column):
        return MONEY_TYPE, "금액", "z1026 원화=정수·외화 2자리 / 부동소수점 금지"
    if d == "INTEGER":
        return "bigint", "정수", "-"
    return "double precision", "실수(비금액)", "-"


def build_table(name: str, cols: list, pk_cols: list) -> tuple:
    """CREATE TABLE 문과 컬럼별 매핑 내역을 만든다.
    cols = PRAGMA table_info 결과 · pk_cols = 기본키 컬럼명 목록"""
    defs, mapping = [], []
    composite = len(pk_cols) > 1
    for c in cols:
        cid, cname, decl, notnull, dflt, pk = c
        typ, kind, rule = classify(name, cname, decl)
        if pk and not composite and (decl or "").upper().startswith("INTEGER"):
            defs.append(f'"{cname}" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
            typ, kind = "bigint identity", "기본키(자동증가)"
        else:
            defs.append(f'"{cname}" {typ}')
        mapping.append((name, cname, decl or "(무타입)", typ, kind, rule))
    if composite:
        defs.append("PRIMARY KEY (" + ", ".join(f'"{x}"' for x in pk_cols) + ")")
    ddl = f'CREATE TABLE "{name}" (\n  ' + ",\n  ".join(defs) + "\n)"
    return ddl, mapping
